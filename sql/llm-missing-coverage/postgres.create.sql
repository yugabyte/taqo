CREATE TABLE lmc_main
(
    c_int      int,
    c_grp      int,
    c_bool     boolean,
    c_text     text,
    c_num      numeric(12, 2),
    c_float    float8,
    c_ts       timestamp,
    c_date     date,
    c_arr      int[],
    c_json     jsonb,
    c_nullable int,
    PRIMARY KEY (c_int)
);
INSERT INTO lmc_main
SELECT c_int,
       c_int % 100,
       c_int % 7 = 0,
       'val_' || c_int,
       c_int * 1.5,
       c_int * 0.25,
       timestamp '2024-01-01 00:00:00' + c_int * interval '37 minutes',
       date '2024-01-01' + c_int % 365,
       ARRAY [c_int % 10, c_int % 13, c_int % 17],
       jsonb_build_object('k', c_int % 10, 'name', 'n' || c_int % 50, 'tags', jsonb_build_array(c_int % 3, c_int % 5)),
       CASE WHEN c_int % 11 = 0 THEN NULL ELSE c_int % 1000 END
FROM generate_series(1, 10000 * $MULTIPLIER) c_int;
CREATE INDEX lmc_main_grp_idx ON lmc_main (c_grp, c_int);
CREATE INDEX lmc_main_ts_idx ON lmc_main (c_ts);

CREATE TABLE lmc_small
(
    c_int  int,
    c_grp  int,
    c_text text,
    PRIMARY KEY (c_int)
);
INSERT INTO lmc_small
SELECT c_int, c_int % 100, 'val_' || c_int
FROM generate_series(1, 1000) c_int;
CREATE UNIQUE INDEX lmc_small_text_idx ON lmc_small (c_text);

CREATE TABLE lmc_tree
(
    c_int    int GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000),
    c_parent int,
    c_text   text DEFAULT 'node',
    PRIMARY KEY (c_int)
);
INSERT INTO lmc_tree
SELECT c_int, NULLIF(c_int / 2, 0), 'node_' || c_int
FROM generate_series(1, 1000) c_int;

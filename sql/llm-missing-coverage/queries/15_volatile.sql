SELECT CURRENT_DATE IS NOT NULL AS d,
       CURRENT_TIME IS NOT NULL AS t0,
       CURRENT_TIME(2) IS NOT NULL AS t2,
       CURRENT_TIMESTAMP IS NOT NULL AS ts0,
       CURRENT_TIMESTAMP(3) IS NOT NULL AS ts3,
       LOCALTIME IS NOT NULL AS lt0,
       LOCALTIME(1) IS NOT NULL AS lt1,
       LOCALTIMESTAMP IS NOT NULL AS lts0,
       LOCALTIMESTAMP(4) IS NOT NULL AS lts4;

SELECT CURRENT_ROLE = CURRENT_USER AS r1,
       SESSION_USER IS NOT NULL AS r2,
       USER IS NOT NULL AS r3,
       CURRENT_CATALOG IS NOT NULL AS r4,
       CURRENT_SCHEMA IS NOT NULL AS r5;

SELECT count(*)
FROM lmc_main
WHERE c_ts < LOCALTIMESTAMP
  AND c_date <= CURRENT_DATE + 365;

EXPLAIN ANALYZE VERBOSE SELECT c_grp, count(*) FROM lmc_small GROUP BY c_grp;

EXPLAIN (ANALYZE, COSTS OFF, TIMING OFF, SUMMARY OFF) SELECT c_int FROM lmc_small WHERE c_int < 3;
